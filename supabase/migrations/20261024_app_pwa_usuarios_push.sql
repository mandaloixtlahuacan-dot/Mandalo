-- App web PWA (/app). La corre Víctor en el SQL Editor cuando la quiera.
-- No borra filas, no hace DROP ni TRUNCATE.
--
-- usuarios_app: cuenta de quien pide desde la app (nombre, WhatsApp, hash).
-- sesiones_app: token de sesión. En la cookie va el token; aquí solo su hash.
-- push_subscriptions: avisos del navegador (VAPID).
-- pedidos.origen: 'whatsapp' para lo que ya existe y para los inserts del bot
-- que no mandan la columna. La app escribe 'app' después de insertar.
-- Sin CHECK, para no rechazar un insert del bot.

create table if not exists public.usuarios_app (
  id bigint generated by default as identity primary key,
  telefono text not null unique,
  nombre text not null,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.sesiones_app (
  id bigint generated by default as identity primary key,
  usuario_id bigint not null references public.usuarios_app (id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists sesiones_app_usuario_idx on public.sesiones_app (usuario_id);

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  usuario_id bigint not null references public.usuarios_app (id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now()
);

create index if not exists push_subscriptions_usuario_idx on public.push_subscriptions (usuario_id);

alter table public.pedidos
  add column if not exists origen text not null default 'whatsapp';

alter table public.usuarios_app enable row level security;
alter table public.sesiones_app enable row level security;
alter table public.push_subscriptions enable row level security;

-- Sin políticas para anon ni authenticated.
-- El servidor usa la service role, que no pasa por RLS.
